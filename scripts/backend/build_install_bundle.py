#!/usr/bin/env python3
"""Write backend/sql/dist/sdi-backend-install.sql: every candidate in README apply order.

The bundle is what the owner pastes into the Supabase SQL editor (or runs with psql)
to install the whole backend on a fresh project in one step. Each candidate keeps its
own `begin; ... commit;` wrapper, so a failing candidate rolls back by itself and the
ones before it stay installed; rerunning the bundle on an installed project fails on
the first `create table` and changes nothing.

    python3 scripts/backend/build_install_bundle.py          # write the bundle
    python3 scripts/backend/build_install_bundle.py --check  # fail if it is stale
"""
from __future__ import annotations

import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SQL = ROOT / "backend" / "sql"
OUT = SQL / "dist" / "sdi-backend-install.sql"


def ordered_candidates() -> list[str]:
    readme = (SQL / "README.md").read_text(encoding="utf-8")
    block = re.search(r"<!-- apply-order -->(.*?)<!-- /apply-order -->", readme, re.S)
    if not block:
        raise SystemExit("backend/sql/README.md has no apply-order block")
    return re.findall(r"[a-z0-9-]+\.sql", block.group(1))


def build() -> str:
    names = ordered_candidates()
    parts = ["-- StickDeath Infinity backend install bundle (generated by scripts/backend/build_install_bundle.py).",
             "-- Apply on a fresh Supabase project as the postgres role: paste into the SQL editor or run with psql.",
             f"-- Candidates in README apply order ({len(names)} files). Each keeps its own transaction.", ""]
    for name in names:
        text = (SQL / name).read_text(encoding="utf-8")
        digest = hashlib.sha256(text.encode("utf-8")).hexdigest()[:16]
        parts.append(f"-- ===== {name} (sha256 {digest}) =====")
        parts.append(text.rstrip("\n"))
        parts.append("")
    return "\n".join(parts)


def main(argv: list[str]) -> int:
    bundle = build()
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != bundle:
            print(f"INSTALL_BUNDLE=STALE run {Path(__file__).relative_to(ROOT)}", file=sys.stderr)
            return 1
        print(f"INSTALL_BUNDLE=OK {OUT.relative_to(ROOT)} ({len(bundle)} bytes)")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(bundle, encoding="utf-8")
    print(f"INSTALL_BUNDLE=WRITTEN {OUT.relative_to(ROOT)} ({len(bundle)} bytes, {len(ordered_candidates())} candidates)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
